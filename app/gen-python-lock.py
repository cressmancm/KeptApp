#!/usr/bin/env python3
"""gen-python-lock.py — pin the bundled Python packages, with hashes.

Writes python-requirements.lock from the packages installed in an existing
environment (by default .build/python-env, the one that ships), fetching each
release's file hashes from PyPI. bundle-python.sh installs from the lock with
--require-hashes --no-deps, so a rebuild gets exactly these packages and
nothing a compromised or newly published dependency release could swap in.

To move osxphotos (or anything else) forward: rebuild the env unpinned with
bundle-python.sh --refresh --unlocked, test it, then run this again.

    python3 gen-python-lock.py [path/to/python-env]
"""

import json
import subprocess
import sys
import urllib.request
from pathlib import Path

APP_DIR = Path(__file__).resolve().parent
ENV_DIR = Path(sys.argv[1]) if len(sys.argv) > 1 else APP_DIR / ".build/python-env"
LOCK = APP_DIR / "python-requirements.lock"
# Pruned from the bundle by bundle-python.sh; never shipped.
SKIP = {"pip", "setuptools", "wheel"}

listing = subprocess.run(
    [str(ENV_DIR / "bin/python3"), "-I", "-c",
     "import importlib.metadata as m\n"
     "for d in m.distributions(): print(d.metadata['Name'], d.version)"],
    check=True, capture_output=True, text=True).stdout

packages = sorted(
    {tuple(line.split(" ", 1)) for line in listing.splitlines() if line.strip()},
    key=lambda p: p[0].lower())

lines = [
    "# Generated by gen-python-lock.py — do not edit by hand.",
    "# Every package in the bundled Python environment, pinned with hashes.",
    "",
]
for name, version in packages:
    if name.lower() in SKIP:
        continue
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as response:
        release = json.load(response)
    hashes = sorted({f["digests"]["sha256"] for f in release["urls"]})
    if not hashes:
        sys.exit(f"!!  No files on PyPI for {name}=={version}")
    lines.append(f"{name}=={version} \\")
    lines.extend(f"    --hash=sha256:{h} \\" for h in hashes[:-1])
    lines.append(f"    --hash=sha256:{hashes[-1]}")

LOCK.write_text("\n".join(lines) + "\n")
print(f"Wrote {LOCK.name}: {sum(1 for l in lines if '==' in l)} packages")
