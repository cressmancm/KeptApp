#!/usr/bin/env python3
"""gen-licenses.py — regenerate app/LICENSES.txt from the bundled Python env.

Walks .build/python-env/lib/python3.13/site-packages/*.dist-info, collects each
distribution's declared license and verbatim license text, and appends the
CPython + statically-linked component licenses from licenses/cpython-components/.

Run after bundle-python.sh --refresh, or whenever OSXPHOTOS_VERSION changes:

    ./gen-licenses.py

build.sh runs this on every build and copies the result into
Kept.app/Contents/Resources/LICENSES.txt, so the notices ship with the app.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

APP_DIR = Path(__file__).resolve().parent
ENV_DIR = APP_DIR / ".build" / "python-env"
COMPONENTS_DIR = APP_DIR / "licenses" / "cpython-components"
OUTPUT = APP_DIR / "LICENSES.txt"

RULE = "=" * 78
THIN = "-" * 78

# Statically linked into libpython3.13.dylib, or shipped as a dylib alongside it.
# Verified with otool -L and the version strings in the built interpreter.
# ncurses, libedit and zlib are deliberately absent: those resolve to /usr/lib
# on macOS, so they are used but not redistributed.
CPYTHON_COMPONENTS = [
    ("OpenSSL", "3.5.7", "Apache-2.0", "LICENSE.openssl-3.txt"),
    ("SQLite", "3.53.1", "Public domain", "LICENSE.sqlite.txt"),
    ("Expat (libexpat)", "2.8.1", "MIT", "LICENSE.expat.txt"),
    ("mpdecimal", "4.0.0", "BSD-2-Clause", "LICENSE.mpdecimal.txt"),
    ("bzip2", "1.0.8", "BSD-4-Clause-like", "LICENSE.bzip2.txt"),
    ("XZ Utils (liblzma)", "", "0BSD", "LICENSE.liblzma.txt"),
    ("libffi", "", "MIT", "LICENSE.libffi.txt"),
    ("Tcl/Tk", "9.0.3", "TCL (BSD-style)", "LICENSE.tcl.txt"),
]

# Wheels that ship no license text of their own. The license is taken from the
# distribution metadata; the URL is where the canonical text lives upstream.
NO_TEXT_UPSTREAM = {
    "bpylist2": "https://github.com/parabolala/bpylist2",
    "pytimeparse2": "https://github.com/onegreyonewhite/pytimeparse2",
}
PYOBJC_UPSTREAM = "https://github.com/ronaldoussoren/pyobjc"

HEADER = f"""{RULE}
Kept — Third-Party Licenses
{RULE}

Kept bundles a self-contained Python runtime and the osxphotos export
tool so that no separate installation is required. This file reproduces the
license and copyright notices for everything shipped inside the application
bundle.

Generated by gen-licenses.py from the contents of the bundled environment.
Do not edit by hand — regenerate after changing pinned versions.

{THIN}
osxphotos
{THIN}

The photo export engine at the heart of Kept is osxphotos by Rhet
Turnbull, used unmodified under the MIT license. Kept is not affiliated
with, endorsed by, or supported by the osxphotos project.

    https://github.com/RhetTbull/osxphotos

The full osxphotos license text appears under "Python packages" below.

{THIN}
Source availability
{THIN}

certifi is licensed under the Mozilla Public License 2.0. It is included
unmodified; its source is available at:

    https://github.com/certifi/python-certifi

Every other component listed here is distributed under a permissive license
(MIT, BSD, Apache-2.0, ISC, PSF, or public domain) that imposes no source
distribution requirement. Source for each is available from the project URL
recorded in its package metadata, and from the Python Package Index.

"""


def read_text(path: Path) -> str:
    """Read a license file, tolerating the odd non-UTF-8 byte."""
    return path.read_text(encoding="utf-8", errors="replace").strip()


def parse_metadata(dist_info: Path) -> dict[str, list[str]]:
    """Parse the RFC 822-ish key/value headers of a METADATA file."""
    fields: dict[str, list[str]] = {}
    metadata = dist_info / "METADATA"
    if not metadata.exists():
        return fields
    for line in read_text(metadata).splitlines():
        if not line.strip():
            break  # blank line ends the headers; the long description follows
        match = re.match(r"^([A-Za-z-]+):\s*(.*)$", line)
        if match:
            fields.setdefault(match.group(1), []).append(match.group(2).strip())
    return fields


def declared_license(fields: dict[str, list[str]]) -> str:
    """Best available license identifier, preferring PEP 639 expressions."""
    expression = fields.get("License-Expression", [])
    if expression:
        return expression[0]

    declared = fields.get("License", [])
    if declared and declared[0] and declared[0].upper() != "UNKNOWN":
        # Some packages dump the whole license text into this field.
        first = declared[0].splitlines()[0].strip()
        if len(first) <= 60:
            return first

    classifiers = [
        c[len("License :: ") :]
        for c in fields.get("Classifier", [])
        if c.startswith("License :: ")
    ]
    if classifiers:
        # "OSI Approved :: MIT License" -> "MIT License"
        return classifiers[0].replace("OSI Approved :: ", "").strip()

    return "See license text below"


def license_files(dist_info: Path) -> list[Path]:
    """License texts shipped in the wheel, in either of the two layouts."""
    found: list[Path] = []
    licenses_dir = dist_info / "licenses"
    if licenses_dir.is_dir():
        found.extend(p for p in sorted(licenses_dir.rglob("*")) if p.is_file())
    found.extend(
        p
        for p in sorted(dist_info.iterdir())
        if p.is_file()
        and re.match(r"^(LICENSE|COPYING|NOTICE|AUTHORS)", p.name, re.IGNORECASE)
    )
    return found


def upstream_for(name: str) -> str | None:
    if name in NO_TEXT_UPSTREAM:
        return NO_TEXT_UPSTREAM[name]
    if name.startswith("pyobjc"):
        return PYOBJC_UPSTREAM
    return None


def main() -> int:
    site_packages = ENV_DIR / "lib" / "python3.13" / "site-packages"
    if not site_packages.is_dir():
        sys.exit(f"No bundled environment at {site_packages}. Run ./bundle-python.sh first.")

    dists = sorted(site_packages.glob("*.dist-info"), key=lambda p: p.name.lower())
    if not dists:
        sys.exit(f"No .dist-info directories under {site_packages}.")

    out: list[str] = [HEADER]

    # ---- Summary table -----------------------------------------------------
    out.append(f"{RULE}\nSUMMARY\n{RULE}\n")
    out.append(f"{'Component':<42} {'Version':<12} License")
    out.append(f"{'-' * 42} {'-' * 12} {'-' * 22}")
    out.append(f"{'CPython':<42} {'3.13.14':<12} PSF-2.0")
    for name, version, spdx, _ in CPYTHON_COMPONENTS:
        out.append(f"{name:<42} {version:<12} {spdx}")

    entries = []
    for dist_info in dists:
        name, _, version = dist_info.name[: -len(".dist-info")].rpartition("-")
        fields = parse_metadata(dist_info)
        entries.append((name, version, declared_license(fields), license_files(dist_info)))

    for name, version, spdx, _ in entries:
        out.append(f"{name:<42} {version:<12} {spdx}")
    out.append("")

    # ---- CPython and its statically linked components ----------------------
    out.append(f"{RULE}\nPYTHON RUNTIME\n{RULE}\n")
    out.append(
        "The bundled interpreter is a relocatable CPython 3.13.14 build from\n"
        "python-build-standalone (https://github.com/astral-sh/python-build-standalone).\n"
        "It links libedit rather than GNU readline, and resolves ncurses, libedit and\n"
        "zlib from macOS system libraries; those are used but not redistributed here.\n"
    )

    cpython_license = ENV_DIR / "lib" / "python3.13" / "LICENSE.txt"
    if cpython_license.exists():
        out.append(f"\n{THIN}\nCPython 3.13.14 — Python Software Foundation License 2.0\n{THIN}\n")
        out.append(read_text(cpython_license))
    else:
        print(f"warning: missing {cpython_license}", file=sys.stderr)

    missing_components = []
    for name, version, spdx, filename in CPYTHON_COMPONENTS:
        path = COMPONENTS_DIR / filename
        if not path.exists():
            missing_components.append(filename)
            continue
        label = f"{name} {version}".strip()
        out.append(f"\n{THIN}\n{label} — {spdx}\n{THIN}\n")
        out.append(read_text(path))

    if missing_components:
        sys.exit(f"Missing component license texts in {COMPONENTS_DIR}: {missing_components}")

    # ---- Python packages ---------------------------------------------------
    out.append(f"\n{RULE}\nPYTHON PACKAGES\n{RULE}\n")

    without_text = []
    for name, version, spdx, files in entries:
        out.append(f"\n{THIN}\n{name} {version} — {spdx}\n{THIN}\n")
        if files:
            texts = []
            for path in files:
                text = read_text(path)
                if text and text not in texts:
                    texts.append(text)
            out.append("\n\n".join(texts))
        else:
            without_text.append(name)
            upstream = upstream_for(name)
            note = (
                f"This package ships no license file in its distribution. It is\n"
                f"distributed under: {spdx}."
            )
            if upstream:
                note += f"\nCanonical license text and source: {upstream}"
            out.append(note)

    out.append(f"\n{RULE}\nEnd of third-party licenses.\n{RULE}")

    OUTPUT.write_text("\n".join(out) + "\n", encoding="utf-8")

    print(f"Wrote {OUTPUT} ({OUTPUT.stat().st_size:,} bytes)")
    print(f"  {len(entries)} Python packages, {len(CPYTHON_COMPONENTS)} runtime components")
    if without_text:
        print(f"  {len(without_text)} packages ship no license text: {', '.join(without_text)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
